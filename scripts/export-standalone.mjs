import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Script } from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const dist = resolve(root, 'dist');
const publicDir = resolve(root, 'public');
const inputPath = resolve(dist, 'index.html');
let html = readFileSync(inputPath, 'utf8');

function assetTag(pattern, description) {
  const tag = html.match(pattern);
  if (!tag) throw new Error(`Vite did not produce the expected ${description} tag.`);
  const url = tag[1];
  const path = fileURLToPath(new URL(url, pathToFileURL(inputPath)));
  if (relative(dist, path).startsWith(`..${sep}`)) throw new Error(`Asset escapes dist/: ${url}`);
  return { tag: tag[0], source: readFileSync(path, 'utf8') };
}

html = html.replace(/[ \t]*<script id="file-fallback">[\s\S]*?<\/script>(?:[ \t]*\r?\n)*/, '');
const css = assetTag(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/, 'stylesheet');
const js = assetTag(/<script\b[^>]*type="module"[^>]*src="([^"]+)"[^>]*><\/script>/, 'entry script');
const manifest = JSON.parse(readFileSync(resolve(publicDir, 'audio/manifest.json'), 'utf8'));
if (manifest.tracks.length !== 15 || Object.keys(manifest.effects).length !== 14) {
  throw new Error('The offline release requires all 15 tracks and 14 sound effects.');
}

const mime = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.svg': 'image/svg+xml' };
const assets = {};
for (const name of readdirSync(resolve(publicDir, 'art')).sort()) {
  const extension = name.slice(name.lastIndexOf('.')).toLowerCase();
  if (!mime[extension]) throw new Error(`Unsupported panorama format: ${name}`);
  assets[`art/${name}`] = `data:${mime[extension]};base64,${readFileSync(resolve(publicDir, 'art', name)).toString('base64')}`;
}
const audio = {};
for (const name of new Set([...manifest.tracks.map(t => t.file), ...Object.values(manifest.effects)])) {
  audio[name] = readFileSync(resolve(publicDir, 'audio', name)).toString('base64');
}
if (Object.keys(assets).length !== 6 || Object.keys(audio).length !== 29) {
  throw new Error('Incomplete artwork/audio payload.');
}

// JSON is inert until parsed. Escaping '<' also prevents a premature script end tag.
const payload = JSON.stringify({ manifest, assets, audio }).replace(/</g, '\\u003c');
const favicon = readFileSync(resolve(publicDir, 'favicon.svg')).toString('base64');
html = html.replace(css.tag, () => `<style>\n${css.source.replace(/<\/style/gi, '<\\/style')}\n</style>`);
html = html.replace(/(<link\b[^>]*rel="icon"[^>]*href=")[^"]+("[^>]*>)/, `$1data:image/svg+xml;base64,${favicon}$2`);

// Vite emits one dependency-free ES bundle. An async IIFE preserves its top-level
// awaits while allowing a classic script to run under file:// without CORS.
const bootstrap = `(async function () {
'use strict';
const payloadNode = document.getElementById('gear-lands-assets');
globalThis.__GEAR_LANDS_EMBEDDED__ = JSON.parse(payloadNode.textContent);
payloadNode.remove();
${js.source}
})().catch(function (error) {
  console.error('Gear Lands startup failed:', error);
  const screen = document.getElementById('loading-screen');
  if (screen) {
    screen.hidden = false;
    screen.classList.remove('loaded');
    screen.innerHTML = '<strong>Не удалось запустить Gear Lands</strong><span>Откройте index.html в актуальном Chrome, Edge или Firefox. Если архив скачан не полностью, распакуйте его заново.</span>';
  }
});`;
// Check as a classic script, not as an ES module: this catches accidental imports.
new Script(bootstrap, { filename: 'gear-lands-offline.js' });
const scripts = `<script id="gear-lands-assets" type="application/json">${payload}</script>\n<script>\n${bootstrap.replace(/<\/script/gi, '<\\/script')}\n</script>`;
html = html.replace(js.tag, '');
// Unlike module scripts, classic scripts are not deferred. Put the bootstrap at
// the end of body so the entire game UI exists before the constructor runs.
html = html.replace('</body>', () => `${scripts}\n</body>`);
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build. Edit web/index.html and src/, not this file. -->');
if (/<script\b[^>]*type="module"/.test(html) || /<link\b[^>]*rel="stylesheet"/.test(html)) {
  throw new Error('The standalone release still depends on external code/styles.');
}

const destination = resolve(root, 'index.html');
// Vite can leave indentation behind when the development-only fallback tag is
// removed. Whitespace-only lines carry no game code or asset data.
html = html.replace(/^[ \t]+$/gm, '');
writeFileSync(resolve(dist, '.nojekyll'), '');
writeFileSync(destination, html);
console.log(`Standalone index.html: ${(Buffer.byteLength(html) / 1048576).toFixed(1)} MB, 6 panoramas, 15 tracks, 14 effects; no server or network required.`);
console.log(`GitHub Pages directory: ${dist} (relative asset URLs, .nojekyll included).`);
